import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { getAllJavaScriptQuestions } from './questions-js.mjs';
import { getAllPythonQuestions } from './questions-py.mjs';
import { getAllJavaQuestions } from './questions-java.mjs';
import { getAllCQuestions } from './questions-c.mjs';
import { getAllCppQuestions } from './questions-cpp.mjs';
import { getAllKotlinQuestions } from './questions-kotlin.mjs';
import { getAllSwiftQuestions } from './questions-swift.mjs';
import { getAllDartQuestions } from './questions-dart.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const questionBanks = {
  javascript: getAllJavaScriptQuestions(),
  python: getAllPythonQuestions(),
  java: getAllJavaQuestions(),
  c: getAllCQuestions(),
  cpp: getAllCppQuestions(),
  kotlin: getAllKotlinQuestions(),
  swift: getAllSwiftQuestions(),
  dart: getAllDartQuestions()
};

const allQuestions = [
  ...questionBanks.javascript,
  ...questionBanks.python,
  ...questionBanks.java,
  ...questionBanks.c,
  ...questionBanks.cpp,
  ...questionBanks.kotlin,
  ...questionBanks.swift,
  ...questionBanks.dart
];

console.log(`\n========================================`);
console.log(`📦 TOTAL QUESTIONS COMPILED: ${allQuestions.length}`);
console.log(`========================================`);

for (const [lang, list] of Object.entries(questionBanks)) {
  console.log(`  - ${lang.padEnd(12)}: ${list.length} questions`);
}

// 1. Write public JSON files for client-side lazy fetching
const publicQuizDir = path.join(rootDir, 'public', 'data', 'quiz');
if (!fs.existsSync(publicQuizDir)) {
  fs.mkdirSync(publicQuizDir, { recursive: true });
}

// All questions in one JSON for /quiz page
fs.writeFileSync(
  path.join(publicQuizDir, 'all.json'),
  JSON.stringify(allQuestions, null, 2),
  'utf-8'
);

// Individual language JSON files
for (const [lang, list] of Object.entries(questionBanks)) {
  fs.writeFileSync(
    path.join(publicQuizDir, `${lang}.json`),
    JSON.stringify(list, null, 2),
    'utf-8'
  );
}

// 2. Select Starter Pool (40 questions: 5 from each of the 8 languages, mix of easy & medium)
// This keeps the initial homepage bundle ultra-lean while offering 40 instant offline questions!
const starterPool = [];
for (const [lang, list] of Object.entries(questionBanks)) {
  const easyAndMed = list.filter(q => q.difficulty === 'easy' || q.difficulty === 'medium');
  const selected = (easyAndMed.length >= 5 ? easyAndMed : list).slice(0, 5);
  starterPool.push(...selected);
}

const srcQuizDir = path.join(rootDir, 'src', 'data', 'quiz');
if (!fs.existsSync(srcQuizDir)) {
  fs.mkdirSync(srcQuizDir, { recursive: true });
}

fs.writeFileSync(
  path.join(srcQuizDir, 'starter-pool.ts'),
  `// Auto-generated by scripts/build-quiz-database.mjs
// Lightweight starter pool (40 questions across 8 languages) for instant zero-fetch homepage interaction
import type { QuizQuestion } from './types';

export const starterQuestions: QuizQuestion[] = ${JSON.stringify(starterPool, null, 2)};
`,
  'utf-8'
);

// 3. Generate Manifest
const manifest = {
  totalCount: allQuestions.length,
  languages: Object.fromEntries(
    Object.entries(questionBanks).map(([k, v]) => [k, v.length])
  ),
  difficulties: {
    easy: allQuestions.filter(q => q.difficulty === 'easy').length,
    medium: allQuestions.filter(q => q.difficulty === 'medium').length,
    hard: allQuestions.filter(q => q.difficulty === 'hard').length,
    expert: allQuestions.filter(q => q.difficulty === 'expert').length
  }
};

fs.writeFileSync(
  path.join(srcQuizDir, 'manifest.ts'),
  `// Auto-generated quiz metadata and manifest
export const quizManifest = ${JSON.stringify(manifest, null, 2)} as const;

export const LANGUAGE_META = [
  { id: 'all', name: 'All Languages', count: ${allQuestions.length}, ext: '.*' },
  { id: 'javascript', name: 'JavaScript', count: ${questionBanks.javascript.length}, ext: '.js' },
  { id: 'python', name: 'Python', count: ${questionBanks.python.length}, ext: '.py' },
  { id: 'java', name: 'Java', count: ${questionBanks.java.length}, ext: '.java' },
  { id: 'c', name: 'C', count: ${questionBanks.c.length}, ext: '.c' },
  { id: 'cpp', name: 'C++', count: ${questionBanks.cpp.length}, ext: '.cpp' },
  { id: 'kotlin', name: 'Kotlin', count: ${questionBanks.kotlin.length}, ext: '.kt' },
  { id: 'swift', name: 'Swift', count: ${questionBanks.swift.length}, ext: '.swift' },
  { id: 'dart', name: 'Dart', count: ${questionBanks.dart.length}, ext: '.dart' }
] as const;
`,
  'utf-8'
);

// 4. Generate Daily Selector helper
fs.writeFileSync(
  path.join(srcQuizDir, 'daily.ts'),
  `// Deterministic daily challenge generator
import type { QuizQuestion } from './types';
import { starterQuestions } from './starter-pool';

export function getDailyChallengeNumber(date = new Date()): number {
  const startEpoch = new Date('2026-01-01T00:00:00Z').getTime();
  const todayEpoch = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate())).getTime();
  const diffDays = Math.max(1, Math.floor((todayEpoch - startEpoch) / (1000 * 60 * 60 * 24)));
  return diffDays;
}

export function getDailyChallenge(pool: QuizQuestion[], date = new Date()): { question: QuizQuestion; challengeNumber: number; dateStr: string } {
  const challengeNumber = getDailyChallengeNumber(date);
  const dateStr = date.toISOString().slice(0, 10);
  
  // Hash the dateStr to deterministically pick a question
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % pool.length;
  return {
    question: pool[index],
    challengeNumber,
    dateStr
  };
}
`,
  'utf-8'
);

console.log(`\n✅ Generated public JSONs, starter-pool.ts (40 items), manifest.ts, and daily.ts successfully!`);
